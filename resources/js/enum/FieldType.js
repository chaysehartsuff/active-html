
/**
    * Enum for table field types
 */
export default class FieldType {
    
    static get STRING() { return 'string'; }
    static get NUMBER() { return 'number'; }
    static get BOOLEAN() { return 'boolean'; }
    static get DATE() { return 'date'; }
    static get DATETIME() { return 'datetime'; }
    static get TIME() { return 'time'; }
}
